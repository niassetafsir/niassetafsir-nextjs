def hx(s):
    return ''.join(chr(int(s[i:i + 4], 16)) for i in range(0, len(s), 4))


def main(write=False):
    total = skipped = reverted = 0
    classes = Counter()
    for lesson in sorted(set(FIXES) | set(REVERTS)):
        p = ROOT / f'{lesson:02d}.json'
        L = json.loads(p.read_text(encoding='utf-8'))
        body = L['arabicBody']
        done = 0
        print(f'  lesson {lesson:02d}')
        for off, wrong, right, why in sorted(REVERTS.get(lesson, []), reverse=True):
            bad, good = hx(wrong), hx(right)
            here = body[off:off + len(bad)]
            if here == good:
                skipped += 1
                continue
            assert here == bad, (
                f'lesson {lesson:02d} @{off}: found {[hex(ord(c)) for c in here]}, '
                f'expected {[hex(ord(c)) for c in bad]} - cannot revert')
            assert len(good) == len(bad)
            body = body[:off] + good + body[off + len(bad):]
            print(f'    @{off:<6} REVERT                       {why}')
            done += 1
            reverted += 1
        for off, word, subs, verse, note in sorted(FIXES.get(lesson, []), reverse=True):
            old = hx(word)
            new = list(old)
            for i, cp in subs:
                new[i] = chr(int(cp, 16))
            new = ''.join(new)
            here = body[off:off + len(old)]
            if here == new:
                skipped += 1
                continue
            assert here == old, (
                f'lesson {lesson:02d} @{off}: found '
                f'{[hex(ord(c)) for c in here]}, expected '
                f'{[hex(ord(c)) for c in old]} - the file has moved under this table')
            assert len(new) == len(old)
            body = body[:off] + new + body[off + len(old):]
            for i, cp in subs:
                classes[f'{ord(old[i]):04x}>{cp}'] += 1
            print(f'    @{off:<6} {note:<28} Q {verse}')
            done += 1
            total += 1
        if write and done:
            L['arabicBody'] = body
            p.write_text(json.dumps(L, ensure_ascii=False), encoding='utf-8')
    print(f'\n{reverted} reverted, {total} words completed'
          + (f', {skipped} already done' if skipped else ''))
    for k, v in classes.most_common():
        print(f'  {k}  {v}')
    if write:
        print('WRITTEN')


if __name__ == '__main__':
    main('--write' in sys.argv)
