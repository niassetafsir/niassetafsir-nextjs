#!/usr/bin/env python3
"""
Repairs the letter confusions this scan makes, inside Qur'anic citations only.

THE CONFUSIONS. The scan misreads letters that differ by a dot or by the depth
of a bowl: qaf/fa, ha/jim, dal/dhal, ra/zay, sad/dad, ayn/ghayn, nun/lam, and
b-t-th-n-y for each other (final nun most often comes out as a dotless ya,
U+0649). Inside a citation the aya settles the reading, so these can be repaired
without anyone's judgement. Outside one they cannot, and nothing here touches
prose. 879 words in 55 lessons, 928 letters.

WHERE THE CANDIDATES CAME FROM. scripts/match-verses.js writes
translation-drafts/verse-match-report.json: every span the compiler marked with
( ), guillemets, braces or quotes, with `match: null` for the 8,419 it could not
identify. A span that should be a known aya and matches nothing is where the
damage is. Each unmatched span was re-matched against the Warsh text in
src/data/verse_text.json under a normalisation that folds the confusion classes
together -- so a corrupted span matches its aya again -- and then aligned word
by word. Two passes, because long and short spans need different evidence:

  LONG SPANS (four words or more), 384 words. Aligned against a six-aya window
  round each candidate verse; a word is repaired only where its span neighbours
  align to the aya's neighbours, so an isolated coincidence cannot carry it.
  170 spans came back.

  SHORT SPANS (two or three words), 495 words. Two words cannot be pinned by
  their neighbours, so the test is uniqueness instead: the folded form of the
  whole span is looked up across every two- and three-word window of the mushaf,
  and the span is repaired only if exactly ONE raw reading fits it. Where two
  ayat fit -- `la yazalu` / `la tazalu`, `alam ya`lamu` / `alam ta`lamu`,
  `wa-hum la yuzlamun` / `wa-antum la tuzlamun` -- nothing is repaired, because
  the Qur'an does not settle which one the compiler wrote. That rule threw out
  eleven of the thirteen person-flips the raw scan had proposed.

WHY THE SITES ARE NAMED ONE BY ONE. Both rules over-fire, and they over-fire in
a way that would put a different word into the Shaykh's mouth, so the output of
the rules is not what runs. Every candidate was read in context first. What was
cut:

  - `ILL` for ILLA (missing alif) reads as a corruption of INNA. It is INNA at
    Q 6:95, 16:18, 17:107, 27:76, 32:28, 34:48, 37:168, 60:8, 67:12 -- and ILLA
    at Q 6:158 (`hal yanzuruna illa an ta'tiyahum`) and Q 8:72 (`illa `ala
    qawmin baynakum wa-baynahum mithaq`). The second pair is not repaired.
  - `MI` (mim + dotless ya) is MIN in most places and FI in others, and fa/mim
    is not a confusion this scan makes. Left alone at Q 17:46 (`wa-fi adhanihim
    waqran`), 9:77 (`fi qulubihim ila yawmi yalqawnahu`), 35:39 (`khala'ifa fi
    l-ard`), 30:24 and 2:248 (`inna fi dhalika la-aya`).
  - a short word can align to the wrong occurrence of itself. `MIYYA` at Q 8:45
    is FI'A, not MINHU; `JAN` at Q 3:97 is FA-INNA, not JA'AT; `ALL` at Q 6:48
    is FA-LA, not INNA. None is repaired.
  - a span can be RIGHT and still fold onto a rival aya. `ilayna yurja`un` is
    Q 40:77 exactly as the file has it; the rule folded it onto Q 29:57
    `ilayna turja`un`. Not repaired. Likewise `wa-ma yanbagh` is Q 26:211
    YANBAGHI, glossed `yasihh` two words later -- a missing final ya, which is
    out of scope, not a letter confusion.
  - Q 21:87 was proposed as `yaqdir` off Q 90:5. The compiler glosses it himself
    two words later -- `an lan naqdi `alayhi bi-ma qadaynahu, naqdir laysa `ala
    zahirihi` -- so it is NAQDIR, and only the fa/qaf is repaired there.

WHERE THE COMPILER GLOSSES THE WORD, THAT IS WHAT SETTLES IT. Q 5:113
`wa-tatma'inna qulubuna` is glossed `taskun` in the line itself; Q 2:68 `la
faridun` is glossed `musinna`; Q 20:72 `fa-qdi ma anta qadin` is glossed `iqdi
ma shi'ta`; Q 76:11 `wa-laqqahum nadratan` is glossed `husnan wa-ida'ata wujuh`;
Q 36:45 `wa-ma khalfakum` is glossed `min `adhab al-akhira` against `ma bayna
aydikum` glossed `min `adhab al-dunya`; Q 5:2 `wa-la l-qala'id` is glossed
`wa-qalladahum`; Q 16:36 `haqqat `alayhi l-dalala` is glossed `wajabat`.

NOT TOUCHED, and deliberately: orthographic variants this scan produces
throughout (alif maqsura for ya, a wrong short vowel, a missing alif, hamza seat
variants); Warsh readings that differ from Hafs -- the reference text here is
Warsh `an Nafi`, so a divergence from Hafs is not an error; canonical variant
readings; and anything inside a hadith, a line of poetry, or the running title
of al-Hajj `Umar's Rimah hizb al-rahim `ala nuhur hizb al-rajim, none of which
the Qur'an settles.

THE VERSE COLUMN says which aya carries the repaired reading. It is
informational: what settles a repair is the reading, not the number beside it.
As first written the column was wrong at roughly one site in ten, because it
recorded whichever aya of the search window the aligner had paired the word
with, which for a formula that recurs -- `fa-bi-ayyi ala'i rabbikuma
tukadhdhiban`, thirty-one times in sura 55 -- was an arbitrary one of many. The
column has been recomputed from the repaired text and every entry checked
against src/data/verse_text.json: the aya named here demonstrably contains the
word as repaired. 135 of 877 changed. That check does not make the attribution
unique -- where a formula recurs, a sister aya would satisfy it equally -- so
read the column as "this reading stands at Q x:y", not as "the Shaykh is quoting
Q x:y and nowhere else". Both auditors tested whether any rival aya disagreed at
a repaired slot, and none does.

TWO SITES HAVE BEEN REVERTED and are no longer in this table: Lesson 16 @13075
(Q 6:51 SHAFI`, written here as tattabi`) and Lesson 8 @12249 (Q 3:27 FI
l-nahar, written here as min). Both replaced damage with plausible Arabic.
scripts/complete-quranic-letter-confusions.py does the reverting and says why.

ANCHORING. Nothing here is matched by a typed string: the scan's combining marks
come in an order no keyboard reproduces and text typed into this repo does not
survive transport byte-identical. Each site gives an offset into `arabicBody`,
the exact codepoints expected there, and the index of each letter to swap. Every
swap is one letter for one letter, so lengths and offsets hold while the pass
runs. If a file has moved under the table, the assert fires. Re-running is safe:
a site already carrying the repaired word is skipped.

  python3 scripts/repair-quranic-letter-confusions.py          # dry run
  python3 scripts/repair-quranic-letter-confusions.py --write
"""
